// T-001 (B-01), BR-03, Q-28; ADR-002 разд. 8.3, ADR-004 разд. 4.3.
// Чистые функции пересчёта количеств в тысячные доли и округления.

/**
 * Количество: целые тысячные доли расходной единицы, как `*_milli` в базе.
 * 1,5 яйца = 1500; 250 г = 250000.
 */
export type Milli = number;

/**
 * Ввод в расходной единице (как ввёл пользователь, например 1.5 или 0.0005)
 * → тысячные доли. Одно округление к ближайшему, половина — от нуля.
 * Для конечного входа результат — целое число. T-001 К16, К17.
 */
export function toMilli(amount: number): Milli {
  return roundHalfAway(amount * 1000);
}

/** Округление к ближайшему целому, половина — от нуля. */
export function roundHalfAway(x: number): number {
  return Math.sign(x) * Math.round(Math.abs(x));
}

/**
 * Число упаковок (может быть дробным: 0.5, 1/3) × коэффициент упаковки
 * в тысячных долях → тысячные доли расходной единицы.
 * Одно округление произведения, половина — от нуля. Для конечного входа результат — целое.
 * T-001 К15–К17, BR-03, BR-04.
 */
export function packsToMilli(packs: number, packSizeMilli: Milli): Milli {
  return roundHalfAway(packs * packSizeMilli);
}
